CREATE TABLE inspections (
    id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    hive_id INT UNSIGNED NOT NULL,
    inspected_on DATE NOT NULL,
    inspector_user_id INT UNSIGNED NOT NULL,
    frames_of_bees TINYINT UNSIGNED NOT NULL,
    brood_frames TINYINT UNSIGNED NOT NULL,
    queen_seen TINYINT(1) NOT NULL DEFAULT 0,
    eggs_seen TINYINT(1) NOT NULL DEFAULT 0,
    temperament TINYINT UNSIGNED NOT NULL,
    honey_stores TINYINT UNSIGNED NOT NULL,
    mites_per_300 SMALLINT UNSIGNED NULL,
    disease_notes TEXT NULL,
    actions_taken TEXT NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    KEY idx_inspections_hive (hive_id),
    KEY idx_inspections_date (inspected_on),
    KEY idx_inspections_inspector (inspector_user_id),
    CONSTRAINT fk_inspections_hive FOREIGN KEY (hive_id) REFERENCES hives (id),
    CONSTRAINT fk_inspections_inspector FOREIGN KEY (inspector_user_id) REFERENCES users (id),
    CONSTRAINT chk_inspections_temperament CHECK (temperament BETWEEN 1 AND 5),
    CONSTRAINT chk_inspections_honey CHECK (honey_stores BETWEEN 1 AND 5)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
